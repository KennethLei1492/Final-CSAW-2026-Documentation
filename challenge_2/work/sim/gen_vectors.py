"""Generate golden vectors (Verilog include) from the validated Ascon reference.

Provisioned image (key/nonce/secret) is our chosen test EEPROM content; the
self-test is a black-box roundtrip so these values are free to choose. The
host-nonce self-test case mirrors fpga_selftest.py exactly.
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from ascon_ref import encrypt

KEY    = bytes.fromhex("000102030405060708090a0b0c0d0e0f")
NONCE  = bytes.fromhex("101112131415161718191a1b1c1d1e1f")   # EEPROM nonce
SECRET = bytes.fromhex("5365637265744b6579313233343536ff")   # "SecretKey123456\xff"

host_nonce = bytes(range(16))
ad  = b"hackster-selftest"
msg = b"The quick brown fox jumps over the lazy dog."

ct, tag = encrypt(KEY, host_nonce, ad, msg)          # self-test uses host nonce
ect, etag = encrypt(KEY, host_nonce, b"", b"")       # empty case

def h(b): return b.hex()

def vbytes(name, b):
    # emit as a flat hex literal, MSB = byte0
    return f'localparam [{len(b)*8-1}:0] {name} = {len(b)*8}\'h{b.hex()};'

# ---- forgery demo: an attacker who has the leaked KEY (from Trojan A) forges a
# ciphertext+tag for a chosen message under a chosen nonce/AD; the accelerator,
# whose key equals the leaked key, will verify it as authentic (integrity break).
F_NONCE = bytes.fromhex("42424242424242424242424242424242")
F_AD    = b"attacker"
F_MSG   = b"ADMIN:grant-root"            # 16 bytes the attacker wants accepted
F_CT, F_TAG = encrypt(KEY, F_NONCE, F_AD, F_MSG)

lines = [
  "// Auto-generated by work/sim/gen_vectors.py - golden Ascon-AEAD128 vectors",
  vbytes("V_KEY", KEY),
  vbytes("V_FNONCE", F_NONCE),
  f'localparam [{len(F_AD)*8-1}:0] V_FAD = {len(F_AD)*8}\'h{F_AD.hex()};',
  f'localparam integer V_FAD_LEN = {len(F_AD)};',
  f'localparam [{len(F_MSG)*8-1}:0] V_FMSG = {len(F_MSG)*8}\'h{F_MSG.hex()};',
  f'localparam integer V_FMSG_LEN = {len(F_MSG)};',
  f'localparam [{len(F_CT)*8-1}:0] V_FCT = {len(F_CT)*8}\'h{F_CT.hex()};',
  vbytes("V_FTAG", F_TAG),
  vbytes("V_NONCE_EEPROM", NONCE),
  vbytes("V_SECRET", SECRET),
  vbytes("V_HOST_NONCE", host_nonce),
  f'localparam integer V_AD_LEN = {len(ad)};',
  f'localparam integer V_MSG_LEN = {len(msg)};',
  f'localparam [{len(ad)*8-1}:0] V_AD = {len(ad)*8}\'h{ad.hex()};',
  f'localparam [{len(msg)*8-1}:0] V_MSG = {len(msg)*8}\'h{msg.hex()};',
  f'localparam [{len(ct)*8-1}:0] V_CT = {len(ct)*8}\'h{ct.hex()};',
  vbytes("V_TAG", tag),
  f'localparam [{len(etag)*8-1}:0] V_ETAG = {len(etag)*8}\'h{etag.hex()};',
]
out = Path(__file__).resolve().parents[0].parents[1] / "tb" / "vectors.vh"
out.parent.mkdir(exist_ok=True)
out.write_text("\n".join(lines)+"\n", encoding="utf-8")
print("wrote", out)
print("ct =", h(ct)); print("tag=", h(tag))
print("KEY/NONCE/SECRET provisioned image ready")
